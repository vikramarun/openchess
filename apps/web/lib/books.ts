/** Concatenate books into one probeable set.
 *
 *  The sort is load-bearing, not tidiness: `entriesFor` binary-searches, so
 *  concatenating two individually-sorted books without re-sorting would make
 *  most positions un-findable. */
export function concatBooks(books: BookEntry[][]): BookEntry[] {
  const all = books.flat();
  all.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  return all;
}

const cache = new Map<string, Promise<BookEntry[]>>();

/** Fetch + parse one built-in book, memoized per session. A failed fetch is
 *  evicted so a transient error doesn't poison the slot for the whole session. */
export function loadBook(id: string): Promise<BookEntry[]> {
  const hit = cache.get(id);
  if (hit) return hit;
  const p = fetch(`/books/${id}.bin`)
    .then((r) => {
      if (!r.ok) throw new Error(`book ${id}: HTTP ${r.status}`);
      return r.arrayBuffer();
    })
    .then(parseBook)
    .catch((e) => {
      cache.delete(id);
      throw e;
    });
  cache.set(id, p);
  return p;
}

/** Load every book in a repertoire and merge them into one probeable set.
 *  Resolves to an empty array for an all-empty repertoire. */
export async function loadRepertoire(rep: Repertoire): Promise<BookEntry[]> {
  const ids = selectedBookIds(rep);
  if (ids.length === 0) return [];
  return concatBooks(await Promise.all(ids.map(loadBook)));
}
