// The repertoire layer: which built-in opening books exist, how a user's
// four-slot repertoire is assembled from them, and lazy loading.
//
// A repertoire has two halves — what you open with as White, and what you
// answer with as Black — so it is four slots, not one book. Assembling it is
// literally concatenation: Polyglot is keyed by position, and each built-in
// book only stores the moves of the side that owns it (see
// public/books/BOOKS.md), so a White entry can never match a Black-to-move
// position. `pnpm test:books` pins that property.
//
// This is where a bot's identity mostly comes from, and unlike search tweaks it
// costs no strength — playing the Najdorf every game is established theory, not
// a worse move.

import { parseBook, type BookEntry, type BookPick } from "./polyglot";

export type BookSlot = "white" | "vsE4" | "vsD4" | "vsOther";
/** The six playing styles. Every style exists in every slot, so a repertoire
 *  can be pure (all Sharp) or mixed (Sharp as White, Solid as Black). */
export type BookStyle = "classical" | "sharp" | "solid" | "hypermodern" | "gambit" | "offbeat";

export type BookMeta = {
  id: string;
  label: string;
  slot: BookSlot;
  style: BookStyle;
  /** Transfer size, shown in the picker so a choice never surprises. */
  bytes: number;
};

