/** `null` in a slot means "no book here — play the engine from move one". */
export type Repertoire = {
  white: string | null;
  vsE4: string | null;
  vsD4: string | null;
  vsOther: string | null;
  /** Leave book after this many plies. */
  maxPly: number;
  /** `best` replays the same game every time; `weighted` varies within theory. */
  pick: BookPick;
};

