#!/usr/bin/env bash
# Can THIS checkout's server talk to the escrow that is actually deployed?
#
# The server's ABI is vendored (crates/ledger/abi/ChessEscrow.json) and the
# contract is redeployed far less often than the server, so a contract change
# ships a server that may run against the OLD bytecode for a while. Anything
# that changes a struct the server reads (a mapping getter like
# `tournaments()`), a function signature, or a constructor can make reads fail
# to decode — and those failures surface as `None`/`false`, i.e. silently.
# That exact shape shipped once: a new field in `Tournament` made every
# `tournaments()` read revert to "buffer overrun" against the live v2 escrow,
# breaking tournament creation, payout and settlement bookkeeping, while a
# probe test using a stand-in contract passed.
#
# This deploys the LIVE contract's bytecode (taken from a git ref) on a
# throwaway Anvil and drives THIS checkout's OnchainSettlement against it: game
# open/settle, tournament open/enter/start/settle (direct and Merkle root) and
# the reads behind them. An operation this list doesn't name is NOT covered —
# add it here when the ledger grows one. Run it whenever contracts/ or
# crates/ledger/abi/ changes. (A SIGKILL skips the cleanup trap and leaves the
# two generated zz_* files under crates/ledger; delete them by hand.)
#
# Usage: abi-compat.sh [REPO_ROOT] [LIVE_REF]
#   REPO_ROOT  checkout whose ledger crate is tested (default: git toplevel)
#   LIVE_REF   git ref whose vendored ABI+bytecode matches the deployed escrow
#              (default: origin/main — correct only while main matches the
#              deployment; check docs/deployments.md)
set -euo pipefail
ROOT=$(cd "${1:-$(git rev-parse --show-toplevel)}" && pwd)
REF=${2:-origin/main}
LEDGER="$ROOT/crates/ledger"
JSON="$LEDGER/zz_abi_compat_live.json"
TEST="$LEDGER/tests/zz_abi_compat.rs"
made_tests_dir=0
[ -d "$LEDGER/tests" ] || { mkdir -p "$LEDGER/tests"; made_tests_dir=1; }
cleanup() { rm -f "$JSON" "$TEST"; [ $made_tests_dir = 1 ] && rmdir "$LEDGER/tests" 2>/dev/null || true; }
trap cleanup EXIT

git -C "$ROOT" show "$REF:crates/ledger/abi/ChessEscrow.json" >"$JSON"
echo "live ABI from $REF ($(git -C "$ROOT" rev-parse --short "$REF")) vs ledger at $(git -C "$ROOT" rev-parse --short HEAD)"

python3 - "$JSON" "$LEDGER/src/lib.rs" "$TEST" <<'PY'
import json, re, sys
abi_path, lib_path, out = sys.argv[1:]
abi = json.load(open(abi_path))["abi"]
lib = open(lib_path).read()
ctor = next(x for x in abi if x["type"] == "constructor")["inputs"]
by_name = {"token_": "*usdc.address()", "oracle_": "oracle.address()", "feeRecipient_": "deployer.address()",
           "feeBps_": "0u16", "settleTimeout_": "3600u64", "entryWindow_": "1800u64"}
missing = [i["name"] for i in ctor if i["name"] not in by_name]
if missing:
    sys.exit(f"live constructor has {missing}: teach abi-compat.sh a value for it")
ctor_args = ", ".join(by_name[i["name"]] for i in ctor)
has = lambda f: re.search(rf"async fn {f}\b", lib) is not None
opt = lambda f, code: code if has(f) else f'    rec(&mut r, "{f}", Err("(not in this ledger)".into()), true);\n'
src = f'''//! GENERATED by .claude/skills/test-openchess/scripts/abi-compat.sh — deleted after the run.
use alloy::network::EthereumWallet;
use alloy::node_bindings::Anvil;
use alloy::providers::ProviderBuilder;
use alloy::sol;
use ledger::{{OnchainSettlement, PrivateKeySigner, SettlementSink, U256}};
use uuid::Uuid;

sol!(#[sol(rpc)] LiveEscrow, "zz_abi_compat_live.json");
sol!(#[sol(rpc)] Usdc, "abi/MockUSDC.json");

fn rec(r: &mut Vec<(String, Result<String, String>, bool)>, op: &str, v: Result<String, String>, skip: bool) {{
    println!("  {{:<26}} {{}}", op, match (&v, skip) {{ (Ok(s), _) => format!("ok   {{s}}"), (Err(e), true) => format!("skip {{e}}"), (Err(e), false) => format!("FAIL {{e}}") }});
    r.push((op.into(), v, skip));
}}
fn res<T: std::fmt::Debug>(x: anyhow::Result<T>) -> Result<String, String> {{
    x.map(|v| format!("{{v:?}}")).map_err(|e| format!("{{e:#}}"))
}}
fn some<T: std::fmt::Debug>(x: Option<T>) -> Result<String, String> {{
    x.map(|v| format!("{{v:?}}")).ok_or_else(|| "None (read failed or did not decode)".into())
}}
fn truthy(x: bool, what: &str) -> Result<String, String> {{
    if x {{ Ok("true".into()) }} else {{ Err(format!("false — {{what}}")) }}
}}

#[tokio::test]
async fn server_against_the_live_escrow() -> anyhow::Result<()> {{
    let anvil = Anvil::new().try_spawn()?;
    let url = anvil.endpoint_url();
    let deployer: PrivateKeySigner = anvil.keys()[0].clone().into();
    let oracle: PrivateKeySigner = anvil.keys()[1].clone().into();
    let p1: PrivateKeySigner = anvil.keys()[2].clone().into();
    let p2: PrivateKeySigner = anvil.keys()[3].clone().into();
    let dep = ProviderBuilder::new().wallet(EthereumWallet::from(deployer.clone())).connect_http(url.clone());
    let usdc = Usdc::deploy(&dep).await?;
    let esc = LiveEscrow::deploy(&dep, {ctor_args}).await?;
    let unit = U256::from(1_000_000u64);
    for who in [&p1, &p2] {{
        let p = ProviderBuilder::new().wallet(EthereumWallet::from((*who).clone())).connect_http(url.clone());
        let amt = unit * U256::from(10);
        Usdc::new(*usdc.address(), &p).mint(who.address(), amt).send().await?.get_receipt().await?;
        Usdc::new(*usdc.address(), &p).approve(*esc.address(), amt).send().await?.get_receipt().await?;
        LiveEscrow::new(*esc.address(), &p).deposit(amt).send().await?.get_receipt().await?;
    }}
    let sink = OnchainSettlement::new(url.clone(), *esc.address(), oracle.clone());
    let mut r = Vec::new();
    rec(&mut r, "owner", some(sink.owner().await), false);
    rec(&mut r, "bankroll_of", some(sink.bankroll_of(p1.address()).await), false);

    let gid = Uuid::new_v4();
    rec(&mut r, "open_escrow", res(sink.open_escrow(gid, p1.address(), p2.address(), unit).await), false);
    rec(&mut r, "report_result (draw)", res(sink.report_result(gid, None).await), false);
    rec(&mut r, "is_settled", truthy(sink.is_settled(gid).await, "chain says unsettled"), false);

    let tid = Uuid::new_v4();
    rec(&mut r, "open_tournament", res(sink.open_tournament(tid, unit).await), false);
    rec(&mut r, "enter_tournament p1", res(sink.enter_tournament(tid, p1.address()).await), false);
    rec(&mut r, "enter_tournament p2", res(sink.enter_tournament(tid, p2.address()).await), false);
{opt("start_tournament", '    rec(&mut r, "start_tournament", res(sink.start_tournament(tid).await), false);' + chr(10))}{opt("tournament_deadlines", '    rec(&mut r, "tournament_deadlines", some(sink.tournament_deadlines(tid).await), false);' + chr(10))}    rec(&mut r, "tournament_pool", some(sink.tournament_pool(tid).await), false);
    rec(&mut r, "settle_tournament", res(sink.settle_tournament(tid, vec![p1.address(), p2.address()], vec![unit * U256::from(2), U256::ZERO]).await), false);
    rec(&mut r, "is_tournament_settled", truthy(sink.is_tournament_settled(tid).await, "chain says unsettled"), false);
{opt("tournament_entered", '    rec(&mut r, "tournament_entered", some(sink.tournament_entered(tid, p1.address()).await), false);' + chr(10))}
    // The Merkle-root settlement path, on a second tournament.
    let tid2 = Uuid::new_v4();
    rec(&mut r, "open_tournament (root)", res(sink.open_tournament(tid2, unit).await), false);
    rec(&mut r, "enter_tournament (root)", res(sink.enter_tournament(tid2, p1.address()).await), false);
{opt("start_tournament", '    rec(&mut r, "start_tournament (root)", res(sink.start_tournament(tid2).await), false);' + chr(10))}    rec(&mut r, "settle_tournament_root", res(sink.settle_tournament_root(tid2, vec![(p1.address(), unit)]).await), false);
    rec(&mut r, "is_tournament_settled (root)", truthy(sink.is_tournament_settled(tid2).await, "chain says unsettled"), false);

    let bad: Vec<_> = r.iter().filter(|(_, v, skip)| v.is_err() && !skip).map(|(op, _, _)| op.clone()).collect();
    assert!(bad.is_empty(), "the server cannot operate against the live escrow: {{bad:?}}");
    Ok(())
}}
'''
open(out, "w").write(src)
PY

cd "$ROOT" && cargo test -q -p ledger --test zz_abi_compat -- --nocapture 2>&1 | grep -vE "^\s*(Compiling|warning|Finished|Running)" | grep -v "^$"
